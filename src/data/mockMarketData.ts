// Helper to generate realistic OHLCV historical candlestick data for any asset
export function generateCandlesticks(
  basePrice: number,
  timeframe: '1D' | '5D' | '1M' | '6M' | '1Y' | 'ALL' = '1M',
  pointsCount: number = 48
): CandlestickData[] {
  const result: CandlestickData[] = [];
  let currentPrice = basePrice * 0.92;
  const now = Date.now();
  
  // interval in milliseconds
  let intervalMs = 3600 * 1000; // 1 hour for 1D
  if (timeframe === '5D') intervalMs = 4 * 3600 * 1000;
  if (timeframe === '1M') intervalMs = 24 * 3600 * 1000;
  if (timeframe === '6M') intervalMs = 3 * 24 * 3600 * 1000;
  if (timeframe === '1Y') intervalMs = 7 * 24 * 3600 * 1000;
  if (timeframe === 'ALL') intervalMs = 30 * 24 * 3600 * 1000;

  const volatility = basePrice > 1000 ? 0.012 : 0.02;

  // SMA/EMA buffers
  const closes: number[] = [];

  for (let i = pointsCount - 1; i >= 0; i--) {
    const timestamp = now - i * intervalMs;
    const dateObj = new Date(timestamp);
    const time = timeframe === '1D' 
      ? dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : `${dateObj.getMonth() + 1}/${dateObj.getDate()}`;

    // Random walk with slight upward bias toward current base price
    const drift = (basePrice - currentPrice) / (i + 1);
    const noise = (Math.random() - 0.48) * currentPrice * volatility;
    const open = currentPrice;
    const close = Math.max(open * 0.8, open + drift + noise);
    const high = Math.max(open, close) + Math.random() * currentPrice * (volatility * 0.6);
    const low = Math.min(open, close) - Math.random() * currentPrice * (volatility * 0.6);
    const volume = Math.floor(100000 + Math.random() * 900000);

    closes.push(close);

    // Calculate SMA 20
    let sma20: number | undefined;
    if (closes.length >= 20) {
      const slice = closes.slice(closes.length - 20);
      sma20 = slice.reduce((a, b) => a + b, 0) / 20;
    }

    // Calculate EMA 50 (or simple approx)
    let ema50: number | undefined;
    if (closes.length >= 10) {
      const slice = closes.slice(Math.max(0, closes.length - 50));
      ema50 = slice.reduce((a, b) => a + b, 0) / slice.length;
    }

    // RSI approximation (60-70 zone for bull, 40-50 for neutral)
    const rsi = Math.min(85, Math.max(25, 50 + (close - open) / open * 400 + Math.random() * 10));

    result.push({
      time,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
      sma20: sma20 ? Number(sma20.toFixed(2)) : undefined,
      ema50: ema50 ? Number(ema50.toFixed(2)) : undefined,
      rsi: Number(rsi.toFixed(1)),
    });

    currentPrice = close;
  }

  // Ensure last candle close strictly equals current basePrice
  if (result.length > 0) {
    result[result.length - 1].close = basePrice;
    result[result.length - 1].high = Math.max(result[result.length - 1].high, basePrice);
    result[result.length - 1].low = Math.min(result[result.length - 1].low, basePrice);
  }

  return result;
}

// Generate realistic Order Book / Depth of Market for an asset
export function generateOrderBook(basePrice: number): OrderBook {
  const bids = [];
  const asks = [];
  const step = basePrice * 0.0008;

  let bidTotal = 0;
  for (let i = 1; i <= 8; i++) {
    const price = Number((basePrice - i * step).toFixed(2));
    const size = Number((Math.random() * 40 + 5).toFixed(2));
    bidTotal += size;
    bids.push({ price, size, total: Number(bidTotal.toFixed(2)) });
  }

  let askTotal = 0;
  for (let i = 1; i <= 8; i++) {
    const price = Number((basePrice + i * step).toFixed(2));
    const size = Number((Math.random() * 40 + 5).toFixed(2));
    askTotal += size;
    asks.push({ price, size, total: Number(askTotal.toFixed(2)) });
  }

  return { bids, asks };
}
